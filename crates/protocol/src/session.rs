//! The application-level live session (Stage 14B).
//!
//! A [`Session`] is **application metadata**: who is publishing what, whether it is
//! live, and the names a viewer needs to join it. It is not a transport connection -
//! a QUIC/MoQ connection is a realtime instance a viewer establishes *for* a live
//! session, using the publisher's endpoint advertisements (see `advertisement`).
//! Nothing realtime lives here: no frames, positions, decoder state, statistics or
//! connection state.
//!
//! # Lifecycle
//!
//! ```text
//! Created ──start──▶ Live ──end──▶ Ended
//!    └──────────────end──────────────▲
//! ```
//!
//! `Ended` is terminal. Every session carries a lease deadline, `expires_at` (see
//! below). The durable record is append-only: each transition is a newer
//! version of the same `session_id`, and readers take the newest version the
//! publisher authored (see [`Session::supersedes`]). Times are milliseconds since the
//! Unix epoch, as everywhere else in this crate, and this crate reads no clock: the
//! caller supplies them.
//!
//! # Expiry
//!
//! A `Live` session must not stay joinable forever just because its publisher vanished
//! without publishing `Ended`. So the publisher states a deadline, `expires_at`, when it
//! creates the session, and a session is **joinable at `now`** only while
//! `state == Live && now < expires_at`: at exactly `expires_at` it is expired. Expiry is
//! a *read* rule, evaluated by the reader with its own injected `now`. It is not a fourth
//! state, nothing is rewritten when a reader notices it, and the DNA never consults a
//! clock (a structurally valid old session is still valid). It only stops *new* joins;
//! it does not end anything already connected. Being joinable also needs the publisher's
//! endpoint advertisement to be live (Stage 13): the two rules are a conjunction.

use crate::{endpoint::AgentPubKeyB64, stream::StreamKind};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// The longest title a session may carry, in bytes.
pub const MAX_TITLE_BYTES: usize = 200;

/// Identifier of one live session. Generated by the publisher (this crate cannot:
/// it is also built for wasm32, without a random source).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct SessionId(pub Uuid);

impl std::fmt::Display for SessionId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl std::str::FromStr for SessionId {
    type Err = String;
    fn from_str(s: &str) -> Result<Self, String> {
        Uuid::parse_str(s.trim())
            .map(SessionId)
            .map_err(|e| format!("not a session id: {e}"))
    }
}

/// Where a session is in its life. Ordered: a session only moves forward.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum SessionState {
    Created,
    Live,
    Ended,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Session {
    pub session_id: SessionId,
    /// The publishing agent; must be the author of the record (enforced by the DNA).
    pub publisher: AgentPubKeyB64,
    /// What is being shared.
    pub source: StreamKind,
    pub state: SessionState,
    /// When the session was created.
    pub created_at: i64,
    /// The lease deadline (ms since the Unix epoch): the session is not joinable at or
    /// after it. Always after `created_at`. A record without one reads as `0`, which is
    /// incoherent and so never joinable.
    #[serde(default)]
    pub expires_at: i64,
    /// When it ended: present exactly when `state` is `Ended`.
    #[serde(default)]
    pub ended_at: Option<i64>,
    #[serde(default)]
    pub title: Option<String>,
    /// `None`: public, any viewer with a live endpoint advertisement may join (today's
    /// behaviour, unchanged). `Some(agents)`: only these agents, plus the publisher
    /// itself, may join - enforced by the publisher at connection time (Stage 14F), not
    /// merely by discovery. `#[serde(default)]` so an old-shape record reads as `None`:
    /// unchanged, non-breaking, the same pattern as `expires_at` in Stage 14D.
    #[serde(default)]
    pub allowed: Option<Vec<AgentPubKeyB64>>,
    /// The MoQ namespace and track the media is published under: what a viewer needs,
    /// with the publisher's endpoint, to join.
    pub namespace: String,
    pub track: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SessionError {
    EmptyName,
    TitleTooLong,
    ExpiresNotAfterCreated,
    EndedWithoutTime,
    TimeOnUnendedSession,
    EndedBeforeCreated,
    InvalidTransition {
        from: SessionState,
        to: SessionState,
    },
}

impl std::fmt::Display for SessionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::EmptyName => write!(f, "session namespace and track must not be empty"),
            Self::TitleTooLong => write!(f, "session title is longer than {MAX_TITLE_BYTES} bytes"),
            Self::ExpiresNotAfterCreated => {
                write!(f, "a session's expires_at must be after its created_at")
            }
            Self::EndedWithoutTime => write!(f, "an ended session must state when it ended"),
            Self::TimeOnUnendedSession => {
                write!(f, "only an ended session may state an end time")
            }
            Self::EndedBeforeCreated => write!(f, "a session cannot end before it was created"),
            Self::InvalidTransition { from, to } => {
                write!(f, "a session cannot go from {from:?} to {to:?}")
            }
        }
    }
}

impl std::error::Error for SessionError {}

impl Session {
    /// A new session in state `Created`, whose lease runs out at `expires_at`.
    pub fn new(
        session_id: SessionId,
        publisher: AgentPubKeyB64,
        source: StreamKind,
        created_at: i64,
        expires_at: i64,
        namespace: impl Into<String>,
        track: impl Into<String>,
        title: Option<String>,
    ) -> Result<Self, SessionError> {
        let s = Self {
            session_id,
            publisher,
            source,
            state: SessionState::Created,
            created_at,
            expires_at,
            ended_at: None,
            title,
            allowed: None,
            namespace: namespace.into(),
            track: track.into(),
        };
        s.validate()?;
        Ok(s)
    }

    /// Restrict this session to `allowed` (plus the publisher, always). Chain onto
    /// [`Session::new`] before publishing to create a private session from the start;
    /// publish a later version with a different list to add/remove agents while live
    /// (see the module docs on versioning) - existing connections are unaffected either
    /// way (Stage 14F only gates *new* connections/reconnects).
    pub fn with_allowed(mut self, allowed: Vec<AgentPubKeyB64>) -> Self {
        self.allowed = Some(allowed);
        self
    }

    /// Whether the record is coherent (checked by the DNA and by readers).
    pub fn validate(&self) -> Result<(), SessionError> {
        if self.namespace.is_empty() || self.track.is_empty() {
            return Err(SessionError::EmptyName);
        }
        if self.expires_at <= self.created_at {
            return Err(SessionError::ExpiresNotAfterCreated);
        }
        if self
            .title
            .as_ref()
            .is_some_and(|t| t.len() > MAX_TITLE_BYTES)
        {
            return Err(SessionError::TitleTooLong);
        }
        match (self.state, self.ended_at) {
            (SessionState::Ended, None) => Err(SessionError::EndedWithoutTime),
            (SessionState::Ended, Some(end)) if end < self.created_at => {
                Err(SessionError::EndedBeforeCreated)
            }
            (SessionState::Created | SessionState::Live, Some(_)) => {
                Err(SessionError::TimeOnUnendedSession)
            }
            _ => Ok(()),
        }
    }

    /// `Created` -> `Live`.
    pub fn start(mut self) -> Result<Self, SessionError> {
        self.transition(SessionState::Live)?;
        Ok(self)
    }

    /// `Created` or `Live` -> `Ended` at `ended_at`.
    pub fn end(mut self, ended_at: i64) -> Result<Self, SessionError> {
        self.transition(SessionState::Ended)?;
        self.ended_at = Some(ended_at);
        self.validate()?;
        Ok(self)
    }

    fn transition(&mut self, to: SessionState) -> Result<(), SessionError> {
        let allowed = matches!(
            (self.state, to),
            (SessionState::Created, SessionState::Live)
                | (SessionState::Created, SessionState::Ended)
                | (SessionState::Live, SessionState::Ended)
        );
        if !allowed {
            return Err(SessionError::InvalidTransition {
                from: self.state,
                to,
            });
        }
        self.state = to;
        Ok(())
    }

    /// Whether the recorded state is `Live`. This says nothing about expiry: use
    /// [`Session::is_joinable_at`] to decide whether anyone may join.
    pub fn is_live(&self) -> bool {
        self.state == SessionState::Live
    }

    /// Whether `agent` may join this session: the publisher always may; with no
    /// allowlist, anyone may; with one, only the listed agents. This is the *rule*
    /// `crates/realtime`'s admission check enforces (see `verify_proof`/`agent_allowed`
    /// there) - client-side discovery may also consult it for a friendly message, but
    /// that is UX only, never the security boundary.
    pub fn agent_allowed(&self, agent: &AgentPubKeyB64) -> bool {
        agent == &self.publisher
            || self
                .allowed
                .as_ref()
                .is_none_or(|list| list.contains(agent))
    }

    /// Whether the lease has run out at `now_ms`: true at exactly `expires_at` and after.
    pub fn is_expired_at(&self, now_ms: i64) -> bool {
        now_ms >= self.expires_at
    }

    /// Whether the session may be joined at `now_ms`: `Live` and not yet expired. An
    /// `Ended` session is never joinable, whatever its deadline. (A publisher's
    /// endpoint must also be live; that is a separate, Stage 13 rule.)
    pub fn is_joinable_at(&self, now_ms: i64) -> bool {
        self.is_live() && !self.is_expired_at(now_ms)
    }

    /// Whether `self`, published later by the same publisher, replaces `earlier`:
    /// the same session, moving strictly forward. Nothing follows `Ended`.
    pub fn supersedes(&self, earlier: &Session) -> bool {
        self.session_id == earlier.session_id
            && self.publisher == earlier.publisher
            && earlier.state != SessionState::Ended
            && self.state > earlier.state
    }
}

/// Collapse versions of sessions (given oldest first) to one per id, as the DHT
/// readers do: the first publisher of an id owns it, and only that publisher's later
/// versions that move the session forward replace it. Order of first appearance kept.
pub fn resolve_sessions(versions_oldest_first: impl IntoIterator<Item = Session>) -> Vec<Session> {
    let mut resolved: Vec<Session> = Vec::new();
    for v in versions_oldest_first {
        if v.validate().is_err() {
            continue;
        }
        match resolved.iter_mut().find(|s| s.session_id == v.session_id) {
            None => resolved.push(v),
            Some(existing) if v.supersedes(existing) => *existing = v,
            Some(_) => {}
        }
    }
    resolved
}

#[cfg(test)]
mod tests {
    use super::*;

    fn id(n: u128) -> SessionId {
        SessionId(Uuid::from_u128(n))
    }

    fn created(n: u128, who: &str) -> Session {
        Session::new(
            id(n),
            who.to_string(),
            StreamKind::Screen,
            100,
            1_000,
            "screenshare",
            "screen",
            Some("demo".into()),
        )
        .unwrap()
    }

    #[test]
    fn a_session_starts_created_and_moves_forward_only() {
        let s = created(1, "alice");
        assert_eq!(s.state, SessionState::Created);
        let live = s.clone().start().unwrap();
        assert!(live.is_live());
        let ended = live.clone().end(200).unwrap();
        assert_eq!(
            (ended.state, ended.ended_at),
            (SessionState::Ended, Some(200))
        );
        // Created may end without ever going live.
        assert_eq!(s.end(150).unwrap().state, SessionState::Ended);
        // Nothing goes backwards, and nothing follows Ended.
        for bad in [
            live.clone().start(),
            ended.clone().start(),
            ended.clone().end(300),
        ] {
            assert!(
                matches!(bad, Err(SessionError::InvalidTransition { .. })),
                "{bad:?}"
            );
        }
    }

    #[test]
    fn incoherent_sessions_are_rejected() {
        let ok = created(1, "alice");
        let mut s = ok.clone();
        s.namespace.clear();
        assert_eq!(s.validate(), Err(SessionError::EmptyName));
        let mut s = ok.clone();
        s.track.clear();
        assert_eq!(s.validate(), Err(SessionError::EmptyName));
        let mut s = ok.clone();
        s.title = Some("x".repeat(MAX_TITLE_BYTES + 1));
        assert_eq!(s.validate(), Err(SessionError::TitleTooLong));
        let mut s = ok.clone();
        s.state = SessionState::Ended;
        assert_eq!(s.validate(), Err(SessionError::EndedWithoutTime));
        let mut s = ok.clone();
        s.ended_at = Some(150);
        assert_eq!(s.validate(), Err(SessionError::TimeOnUnendedSession));
        let mut s = ok.clone();
        s.state = SessionState::Ended;
        s.ended_at = Some(99);
        assert_eq!(s.validate(), Err(SessionError::EndedBeforeCreated));
        // The lease must end after the session was created.
        let mut s = ok.clone();
        s.expires_at = s.created_at;
        assert_eq!(s.validate(), Err(SessionError::ExpiresNotAfterCreated));
        s.expires_at = s.created_at - 1;
        assert_eq!(s.validate(), Err(SessionError::ExpiresNotAfterCreated));
        s.expires_at = s.created_at + 1;
        assert_eq!(s.validate(), Ok(()));
        // Ending exactly at creation is allowed.
        assert!(ok.end(100).is_ok());
    }

    #[test]
    fn a_live_session_is_joinable_only_before_its_expiry_and_exactly_at_it_is_expired() {
        let live = created(1, "alice").start().unwrap(); // created 100, expires 1_000
        assert!(live.is_joinable_at(0));
        assert!(live.is_joinable_at(999), "one millisecond before expiry");
        assert!(!live.is_expired_at(999));
        assert!(live.is_expired_at(1_000), "exactly at expiry is expired");
        assert!(!live.is_joinable_at(1_000));
        assert!(!live.is_joinable_at(1_001));
        assert!(!live.is_joinable_at(i64::MAX));
    }

    #[test]
    fn only_a_live_session_is_joinable_whatever_its_deadline() {
        let s = created(1, "alice");
        assert!(!s.is_joinable_at(500), "Created is not joinable yet");
        let live = s.clone().start().unwrap();
        assert!(live.is_joinable_at(500));
        // Ended is never joinable, even well before its deadline.
        let ended = live.end(200).unwrap();
        assert_eq!(ended.expires_at, 1_000, "ending keeps the deadline");
        assert!(!ended.is_joinable_at(500));
        assert!(!ended.is_joinable_at(0));
        // Ending after the deadline is still a valid record.
        assert!(created(2, "alice").start().unwrap().end(5_000).is_ok());
    }

    #[test]
    fn a_session_serializes_and_optional_fields_default() {
        let s = created(7, "alice").start().unwrap();
        let json = serde_json::to_string(&s).unwrap();
        assert_eq!(serde_json::from_str::<Session>(&json).unwrap(), s);
        let mut v: serde_json::Value = serde_json::from_str(&json).unwrap();
        v.as_object_mut().unwrap().remove("ended_at");
        v.as_object_mut().unwrap().remove("title");
        v.as_object_mut().unwrap().remove("expires_at");
        let back: Session = serde_json::from_value(v).unwrap();
        assert_eq!((back.ended_at, back.title.clone()), (None, None));
        // A record with no lease reads as 0: incoherent, so never valid or joinable.
        assert_eq!(back.expires_at, 0);
        assert_eq!(back.validate(), Err(SessionError::ExpiresNotAfterCreated));
        assert!(!back.is_joinable_at(0));
    }

    #[test]
    fn session_ids_display_and_parse() {
        let a = id(0xA11CE);
        assert_eq!(a.to_string().parse::<SessionId>().unwrap(), a);
        assert!("not-a-uuid".parse::<SessionId>().is_err());
    }

    #[test]
    fn readers_keep_the_newest_forward_version_owned_by_the_first_publisher() {
        let s1 = created(1, "alice");
        let live = s1.clone().start().unwrap();
        let ended = live.clone().end(200).unwrap();
        let s2 = created(2, "alice");

        let got = resolve_sessions([s1.clone(), s2.clone(), live.clone()]);
        assert_eq!(got, vec![live.clone(), s2.clone()]);

        // Ended is terminal: a later "Live" for the same id cannot revive it.
        let got = resolve_sessions([s1.clone(), live.clone(), ended.clone(), live.clone()]);
        assert_eq!(got, vec![ended]);

        // Another agent cannot take over or end someone else's session id.
        let mut squat = created(1, "mallory").start().unwrap();
        let got = resolve_sessions([s1.clone(), squat.clone()]);
        assert_eq!(got, vec![s1.clone()]);
        squat.state = SessionState::Ended;
        squat.ended_at = Some(300);
        assert_eq!(resolve_sessions([live.clone(), squat]), vec![live]);
    }

    #[test]
    fn incoherent_versions_are_ignored_by_readers() {
        let s = created(1, "alice");
        let mut bad = s.clone().start().unwrap();
        bad.namespace.clear();
        assert_eq!(resolve_sessions([s.clone(), bad]), vec![s]);
    }
}
