//! Stage 14F: how the admission-proof handshake travels over MoQT for a *private*
//! session. Wire framing only - what is signed and how it is verified is
//! `holochain_moq_protocol::admission`'s job, not this module's.
//!
//! ```text
//! publisher session task                              viewer subscribe task
//!   (only for a private session's connection)
//!   challenge = SHA-256(QUIC connection id)   ────    challenge = SHA-256(QUIC connection id)
//!   (both sides derive it independently -                (the id is known to both sides from
//!    nothing is transmitted for this step)                the handshake itself, before any
//!                                                          MoQT track/namespace machinery)
//!   subscribe to the *existing* reverse       ◀──────  sign it (holochain_moq_protocol),
//!   CONTROL_NAMESPACE/CONTROL_TRACK,                     publish an AdmissionProof object
//!   read one object of kind KIND_ADMISSION_PROOF          on that same reverse track
//!   verify_proof(...) before publish_namespace
//! ```
//!
//! A *public* session (`Session.allowed == None`) never touches any of this: neither
//! side subscribes to or publishes anything here, and the existing zero-overhead path
//! (`publish_namespace` called immediately) is unchanged - see `live.rs`/`subscribe.rs`.
//!
//! The reverse control track already carries keyframe requests
//! ([`crate::recovery`]); an admission proof is a **distinct `kind`** on that same
//! track (never overloading [`crate::recovery::decode_request`]'s format), per the
//! Stage 14F brief.
//!
//! # Challenge derivation - a documented deviation from a transmitted challenge
//!
//! The Stage 14F brief calls for "a fresh publisher-generated challenge". The pinned
//! `moq-transport` 0.16.2 `Publisher::publish_namespace` can only be called **once**
//! per `Publisher` (a second call panics - confirmed empirically), so the originally
//! designed mechanism - publish a one-shot challenge track, then separately
//! `publish_namespace` the real content - is not implementable against this library
//! version without a second, disallowed `publish_namespace` call.
//!
//! Instead, both sides independently derive the challenge as
//! `SHA-256(QUIC connection id)`. The connection id is generated by the QUIC/TLS
//! handshake itself, is unique per connection attempt by construction, is known to
//! both endpoints before any MoQT track/namespace ceremony, and cannot be predicted or
//! chosen by the viewer in advance (it is a product of the handshake, not a
//! viewer-supplied value). This preserves freshness-per-connection and unpredictability
//! from the viewer's perspective, but it is not "publisher-generated" in the literal
//! sense of a value the publisher invents and unilaterally transmits - it is a value
//! both sides compute identically from a handshake artifact neither side alone
//! controls. Signing is still bound to the exact session id, the domain-separation
//! context, and the claimed agent key (see `holochain_moq_protocol::admission`), so a
//! proof still cannot be replayed across sessions or connections.
//!
//! # Refusal signalling (Stage 15.2)
//!
//! When `live::admit` fails, the publisher ends that session with
//! [`ADMISSION_REFUSED_CODE`] *after* failing closed and strictly before
//! `publish_namespace`; the viewer reports it as [`AdmissionRefused`] (not `TransportLost`),
//! so the reconnect layer stops instead of retrying. This adds a signal on the refusal
//! path only. It does not change when, or whether, media is exposed.
//!
//! # Documented limitation
//!
//! With the current `moq_native_ietf` wrapper, WebTransport/MoQ session establishment
//! occurs before the application-level admission proof. Therefore an unauthorized peer
//! may create a transient transport/MoQ session, but it cannot receive media, obtain
//! the published media namespace, or influence encoding before authorization.

use anyhow::{bail, Result};
use bytes::{BufMut, Bytes, BytesMut};
use holochain_moq_protocol::{AgentPubKeyB64, Challenge};
use sha2::{Digest, Sha256};

const WIRE_VERSION: u8 = 1;
const KIND_ADMISSION_PROOF: u8 = 2; // KIND_KEYFRAME_REQUEST (crate::recovery) = 1
const CHALLENGE_LEN: usize = 32;
const SIGNATURE_LEN: usize = 64;

/// A Holochain `AgentPubKeyB64` (`holo_hash`'s `'u' + base64url-no-pad(39 bytes)` form)
/// is always exactly this many ASCII bytes - see `holochain_moq_protocol::admission`.
const AGENT_B64_LEN: usize = 53;

/// How long a connecting session has, after its challenge is published, to present a
/// valid proof before the publisher gives up and closes it. Bounded and short: this is
/// one connection setup step, not a session-long allowance.
pub const AUTH_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(5);

/// Application close code a publisher ends a *refused* session with (Stage 15.2).
///
/// Before this, a refused viewer saw only a generic `connection error: closed` - exactly
/// what a crashed publisher looks like - so the reconnect layer retried a permanent
/// refusal as if it were a transient loss. The publisher sends this code only after
/// `live::admit` has failed, i.e. strictly before `publish_namespace`: it adds a signal on
/// the refusal path and changes nothing about *when* or *whether* media is exposed.
/// (ASCII "AD".) A hostile publisher can send it too, but that only ever ends the
/// viewer's attempt to join *that* publisher, which the publisher could do anyway.
pub const ADMISSION_REFUSED_CODE: u32 = 0x4144;
pub const ADMISSION_REFUSED_REASON: &str = "admission refused";

/// The publisher definitively refused this viewer's admission (Stage 15.2). Deliberately
/// **not** [`crate::TransportLost`]: a lost transport is worth retrying, a refusal will
/// not change by trying again. See [`is_admission_refused`].
#[derive(Debug, thiserror::Error)]
#[error("the publisher refused admission to this session")]
pub struct AdmissionRefused;

/// Is this (or any error it wraps) an [`AdmissionRefused`]?
pub fn is_admission_refused(err: &anyhow::Error) -> bool {
    err.chain().any(|e| e.is::<AdmissionRefused>())
}

/// Derives the admission challenge from the QUIC connection id, shared by both
/// endpoints as of the handshake itself. See the module-level "Challenge derivation"
/// section for why this replaces a separately transmitted challenge value.
pub fn challenge_from_connection_id(connection_id: &str) -> Challenge {
    let mut hasher = Sha256::new();
    hasher.update(connection_id.as_bytes());
    let digest = hasher.finalize();
    let mut challenge: Challenge = [0u8; CHALLENGE_LEN];
    challenge.copy_from_slice(&digest);
    challenge
}

/// `version:u8 = 1`, `kind:u8 = 2 (admission proof)`, `agent:[u8; 53]` (ASCII
/// `AgentPubKeyB64`), `signature:[u8; 64]`. An object of [`crate::recovery`]'s
/// `KIND_KEYFRAME_REQUEST` (10 bytes) can never be mistaken for this (different length
/// and a different `kind` byte); [`crate::recovery::decode_request`] and this decoder
/// each reject the other's shape outright.
pub fn encode_proof(agent: &AgentPubKeyB64, signature: &[u8; SIGNATURE_LEN]) -> Result<Bytes> {
    if agent.len() != AGENT_B64_LEN || !agent.is_ascii() {
        bail!("not a well-formed AgentPubKeyB64: {agent:?}");
    }
    let mut b = BytesMut::with_capacity(1 + 1 + AGENT_B64_LEN + SIGNATURE_LEN);
    b.put_u8(WIRE_VERSION);
    b.put_u8(KIND_ADMISSION_PROOF);
    b.put_slice(agent.as_bytes());
    b.put_slice(signature);
    Ok(b.freeze())
}

pub fn decode_proof(bytes: &[u8]) -> Result<(AgentPubKeyB64, [u8; SIGNATURE_LEN])> {
    let expected = 1 + 1 + AGENT_B64_LEN + SIGNATURE_LEN;
    if bytes.len() != expected {
        bail!(
            "admission-proof object must be {expected} bytes, got {}",
            bytes.len()
        );
    }
    if bytes[0] != WIRE_VERSION || bytes[1] != KIND_ADMISSION_PROOF {
        bail!(
            "not an admission-proof control message ({}/{})",
            bytes[0],
            bytes[1]
        );
    }
    let agent = std::str::from_utf8(&bytes[2..2 + AGENT_B64_LEN])
        .map_err(|e| anyhow::anyhow!("agent field is not valid UTF-8: {e}"))?
        .to_string();
    let mut signature = [0u8; SIGNATURE_LEN];
    signature.copy_from_slice(&bytes[2 + AGENT_B64_LEN..]);
    Ok((agent, signature))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn challenge_derivation_is_deterministic_and_distinguishes_connections() {
        let a1 = challenge_from_connection_id("conn-a");
        let a2 = challenge_from_connection_id("conn-a");
        let b = challenge_from_connection_id("conn-b");
        assert_eq!(a1, a2, "both sides of the same connection must agree");
        assert_ne!(a1, b, "different connections must get different challenges");
        assert_eq!(a1.len(), 32);
    }

    #[test]
    fn proofs_round_trip_and_reject_garbage() {
        let agent = "u".to_string() + &"A".repeat(AGENT_B64_LEN - 1);
        let sig = [3u8; 64];
        let encoded = encode_proof(&agent, &sig).unwrap();
        let (a, s) = decode_proof(&encoded).unwrap();
        assert_eq!((a, s), (agent.clone(), sig));

        assert!(encode_proof(&"too-short".to_string(), &sig).is_err());
        assert!(decode_proof(b"short").is_err());
        let mut bad = encoded.to_vec();
        bad[1] = 1; // a keyframe-request kind byte, not an admission proof
        assert!(decode_proof(&bad).is_err());
    }

    /// The two message *kinds* on the shared reverse control track can never collide:
    /// different fixed lengths, and a `kind` byte that always disagrees.
    #[test]
    fn admission_proofs_and_keyframe_requests_are_never_confused() {
        use crate::recovery::{decode_request, encode_request};
        let agent = "u".to_string() + &"A".repeat(AGENT_B64_LEN - 1);
        let proof = encode_proof(&agent, &[0u8; 64]).unwrap();
        let keyframe = encode_request(42);
        assert_ne!(proof.len(), keyframe.len());
        assert!(decode_request(&proof).is_err());
        assert!(decode_proof(&keyframe).is_err());
    }
}
